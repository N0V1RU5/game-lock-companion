def set_lang(lang: str | None):
    global _lang
    _lang = lang if lang in LANGS else "cs"


def get_lang() -> str:
    return _lang


def T(key: str, **fmt) -> str:
    entry = STR.get(key)
    if entry is None:
        return key
    text = entry.get(_lang) or entry.get("cs") or key
    return text.format(**fmt) if fmt else text
